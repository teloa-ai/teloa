"""从固定 LVGL 输入字体生成 Teloa CJK 回退；不依赖旧设备资源或在线字形推送。"""
import hashlib
import json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

root=Path(__file__).resolve().parents[1]
source=root/'managed_components/lvgl__lvgl/scripts/built_in_font/SourceHanSansSC-Normal.otf'
target=root/'main/teloa/assets'
font=ImageFont.truetype(str(source),20)
characters=set()
for first in range(0xa1,0xf8):
    for second in range(0xa1,0xff):
        try:char=bytes((first,second)).decode('gb2312')
        except UnicodeDecodeError:continue
        if 0x3400<=ord(char)<=0x9fff:characters.add(char)
for path in (root/'main/teloa').glob('*'):
    if path.suffix in ('.cc','.h'):characters.update(char for char in path.read_text() if 0x3400<=ord(char)<=0x9fff)
bitmap=bytearray();glyphs=['{0}'];codes=[]
for char in sorted(characters):
    box=font.getbbox(char,anchor='ls');width,height=box[2]-box[0],box[3]-box[1]
    image=Image.new('L',(width,height));ImageDraw.Draw(image).text((-box[0],-box[1]),char,font=font,fill=255,anchor='ls')
    pixels=list(image.get_flattened_data());data=bytearray((len(pixels)+7)//8)
    for i,pixel in enumerate(pixels):
        if pixel>=100:data[i//8]|=1<<(7-i%8)
    glyphs.append('{.bitmap_index=%d,.adv_w=320,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}'%(len(bitmap),width,height,box[0],-box[3]));bitmap.extend(data);codes.append(ord(char))
start=min(codes)
text='''/* Generated by tools/build_font.py. Font derivative licensed under SIL OFL 1.1.
 * Copyright 2014-2021 Adobe. See OFL-font.txt. Derivative name: Teloa CJK. */
#include <lvgl.h>
static const uint8_t bitmap[]={\n'''
text+='\n'.join(','.join(str(byte) for byte in bitmap[i:i+32])+',' for i in range(0,len(bitmap),32))+'\n};\n'
text+='static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={\n'+',\n'.join(glyphs)+'\n};\n'
text+='static const uint16_t codes[]={'+','.join(str(code-start) for code in codes)+'};\n'
text+='static const lv_font_fmt_txt_cmap_t cmaps[]={{.range_start=%d,.range_length=%d,.glyph_id_start=1,.unicode_list=codes,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};\n'%(start,max(codes)-start+1,len(codes))
text+='static lv_font_fmt_txt_dsc_t descriptor={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.bpp=1,.cmap_num=1};\n'
text+='const lv_font_t teloa_cjk_20={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=28,.base_line=8,.underline_position=-2,.underline_thickness=1,.dsc=&descriptor};\n'
(target/'teloa_cjk_20.c').write_text(text)
(target/'font-manifest.json').write_text(json.dumps({'schema':1,'source':'LVGL 9.5.0 bundled SourceHanSansSC-Normal.otf','sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'derivative':'Teloa CJK 20px 1bpp','license':'SIL-OFL-1.1','glyphCount':len(codes),'bitmapBytes':len(bitmap),'outputSha256':hashlib.sha256(text.encode()).hexdigest()},ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'glyphs':len(codes),'bitmapBytes':len(bitmap)}))
