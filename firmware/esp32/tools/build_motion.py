"""生成固件动作表。预览直接读取同一份 motion.json，不维护第二套动作。"""
import argparse,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def generate():
    spec=json.loads((ROOT/'main/teloa/motion.json').read_text())
    lines=['// Generated by tools/build_motion.py; edit motion.json instead.','#pragma once','namespace teloa::motion_data {']
    lines.append('inline constexpr uint32_t transition_ms=%d,frame_ms=%d,quiet_frame_ms=%d;'%(spec['transitionMs'],spec['frameMs'],spec['quietFrameMs']))
    lines.append('inline constexpr int origin_x=%d,origin_y=%d;'%(spec['origin']['x'],spec['origin']['y']))
    for name,clip in spec['clips'].items():
        frames=clip['frames']
        if frames[0]['at']!=0 or len(frames)<2:raise ValueError('动作必须从零开始')
        previous=-1
        lines.append('inline constexpr MotionKeyframe '+name+'[]={')
        for f in frames:
            if f['at']<=previous or not (-40<=f['x']<=40 and -14<=f['y']<=12) or not 0<=f['pose']<6:raise ValueError('动作越界或时间不连续')
            previous=f['at']
            lines.append('    {%d,%d,%d,%d,%d,%d,%d,"%s","%s",%d},'%(f['at'],f['x'],f['y'],f['angle'],f['sx'],f['sy'],f['pose'],f['activity'],f['prop'],f['signal']))
        lines.append('};')
    lines.append('inline constexpr MotionClip clips[]={')
    for name,clip in spec['clips'].items():lines.append('    {"%s",%s,sizeof(%s)/sizeof(MotionKeyframe),%s},'%(name,name,name,'true' if clip['loop'] else 'false'))
    lines+=['};','}  // namespace teloa::motion_data','']
    return '\n'.join(lines)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    target=ROOT/'main/teloa/teloa_motion_data.h';text=generate()
    if args.check:
        if target.read_text()!=text:raise SystemExit('动作表需要重新生成。')
    else:target.write_text(text)
if __name__=='__main__':main()
