"""确定性打包已定稿小松鼠：统一色板、独立 alpha、逐帧压缩；不生成角色。"""
import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path
from PIL import Image, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[1]
POSES = ('standing', 'wink', 'curious', 'thinking', 'reading', 'celebrating')
WIDTH = HEIGHT = 176
PIXELS = WIDTH*HEIGHT

def decode_pack(data):
    """供离线预览使用，格式和固件一致，不读候选图集。"""
    magic, version, width, height, colors, count = struct.unpack_from('<4sHHHHI', data)
    assert (magic, version, width, height, colors, count) == (b'TPET', 1, WIDTH, HEIGHT, 256, 54)
    palette = data[16:784]
    images = []
    for i in range(count):
        offset, length = struct.unpack_from('<II', data, 784+i*8)
        raw = zlib.decompress(data[offset:offset+length])
        assert len(raw) == PIXELS*3//2
        output = bytearray(PIXELS*4)
        for p in range(PIXELS):
            c = raw[p]*3
            alpha = raw[PIXELS+p//2]
            output[p*4:p*4+4] = bytes((*palette[c:c+3], ((alpha>>4) if p%2==0 else alpha&15)*17))
        images.append(Image.frombytes('RGBA', (WIDTH, HEIGHT), bytes(output)))
    return images

def build():
    if pillow_version != '12.2.0':
        raise RuntimeError('请使用 requirements-assets.txt 固定的 Pillow 12.2.0')
    source = ROOT/'artwork/companion'
    frames, inputs = [], {}
    for name in POSES:
        path = source/f'{name}.webp'
        image = Image.open(path).convert('RGBA').resize((160,160), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', (WIDTH, HEIGHT))
        canvas.alpha_composite(image, (8,10))
        frames.append(canvas)
        inputs[f'{name}.webp'] = hashlib.sha256(path.read_bytes()).hexdigest()
    spec = json.loads((source/'animation.json').read_text())
    for clip in spec['clips']:
        assert len(spec['clips'][clip]) == 16 and all(50 <= d <= 1000 for d in spec['clips'][clip])
        for i in range(16):
            path = source/'frames'/f'{clip}-{i:02}.png'
            image = Image.open(path).convert('RGBA')
            assert image.size == (WIDTH,HEIGHT)
            frames.append(image)
            inputs[f'frames/{path.name}'] = hashlib.sha256(path.read_bytes()).hexdigest()
    assert len(frames) == 54
    contact = Image.new('RGB', (WIDTH, HEIGHT*len(frames)))
    for i, image in enumerate(frames):
        contact.paste(image.convert('RGB'), (0, i*HEIGHT))
    palette = contact.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    rgb = bytes(palette.getpalette()[:768])
    payloads = []
    for image in frames:
        indices = bytearray(image.convert('RGB').quantize(palette=palette, dither=Image.Dither.NONE).tobytes())
        alpha = image.getchannel('A').tobytes()
        for i, value in enumerate(alpha):
            if value < 8:
                indices[i] = 0
        packed_alpha = bytes(((alpha[i]+8)//17<<4)|((alpha[i+1]+8)//17) for i in range(0,PIXELS,2))
        payloads.append(zlib.compress(indices+packed_alpha, 9))
    offset = 16+768+len(frames)*8
    table = bytearray()
    for data in payloads:
        table.extend(struct.pack('<II', offset, len(data)))
        offset += len(data)
    pack = struct.pack('<4sHHHHI', b'TPET', 1, WIDTH, HEIGHT, 256, len(frames))+rgb+table+b''.join(payloads)
    decoded = decode_pack(pack)
    error_sum = weight_sum = 0
    for original, image in zip(frames, decoded):
        for a, b in zip(original.get_flattened_data(), image.get_flattened_data()):
            weight_sum += a[3]*3
            error_sum += sum(abs(a[c]-b[c])*a[3] for c in range(3))
    manifest = {'schema':2, 'width':WIDTH, 'height':HEIGHT, 'frames':54,
                'format':'TPET/1: shared RGB256, separate A4, zlib per frame',
                'pillow':pillow_version, 'zlib':zlib.ZLIB_VERSION, 'inputs':inputs,
                'packBytes':len(pack), 'packSha256':hashlib.sha256(pack).hexdigest(),
                'maxAlphaError':8, 'alphaWeightedRgbMeanAbsoluteError':round(error_sum/weight_sum,3),
                'decodedBgraSha256':[hashlib.sha256(im.tobytes('raw','BGRA')).hexdigest() for im in decoded]}
    definitions = ['// Generated by tools/build_mascot.py; edit artwork/companion/animation.json.',
                   '#pragma once', 'namespace teloa::sprite_data {']
    clip_starts = {name:6+16*i for i,name in enumerate(spec['clips'])}
    total = 0
    for i, phase in enumerate(spec['daily']):
        durations = spec['clips'][phase['clip']] if 'clip' in phase else [phase['duration']]
        definitions.append('inline constexpr uint16_t durations_%d[]={%s};' % (i,','.join(map(str,durations))))
        total += sum(durations)*phase.get('repeats',1)
    definitions.append('inline constexpr SpritePhase phases[]={')
    for i, phase in enumerate(spec['daily']):
        first = clip_starts[phase['clip']] if 'clip' in phase else phase['pose']
        count = 16 if 'clip' in phase else 1
        definitions.append('{%d,%d,durations_%d,%d,"%s","%s"},' % (first,count,i,phase.get('repeats',1),phase['activity'],phase.get('prop','none')))
    definitions.extend(['};',f'inline constexpr uint32_t cycle_ms={total};','}'])
    fallback = frames[0].crop((8,10,168,170)).resize((64,64), Image.Resampling.LANCZOS).tobytes('raw','BGRA')
    return {'mascot.pet':pack, 'mascot-manifest.json':(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode(),
            'teloa_sprite_data.h':('\n'.join(definitions)+'\n').encode(), 'fallback.rgba':fallback}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    for name, content in build().items():
        path = ROOT/'main/teloa/assets'/name
        if args.check:
            if not path.is_file() or path.read_bytes()!=content:
                raise RuntimeError(f'资源不匹配，请重新打包：{name}')
        else:
            path.write_bytes(content)

if __name__=='__main__':main()
