import {createElement,useEffect,useState,useSyncExternalStore,type ComponentType} from 'react'
import {Check,Copy} from 'lucide-react'
import type {PropsRuntime,StoredEntry} from '@deepseek-ai/dsh-client-ui-slots'
import {MarkdownPreview} from './knowledge-markdown.js'
import {readHostReviewDelivery,verifyHostReviewDelivery,type HostReviewDelivery} from './delivery-review-presentation.js'
import {useI18n} from './i18n/provider.js'
import {ToolbarIconButton} from './ToolbarIconButton.js'
import css from './DeliveryReviewContextView.module.css'

type ContextProps=PropsRuntime<'conversation.chat.node','context'>
type Renderer={subscribe:(listener:()=>void)=>()=>void;getSnapshot:()=>readonly StoredEntry[];isLive:(entry:StoredEntry)=>boolean}

/** 借用原生 context keyed renderer（priority 0 的官方占位）；不复制其行、展开或正文实现。 */
function nativeContextRenderer(entries:readonly StoredEntry[],isLive:(entry:StoredEntry)=>boolean):{component:ComponentType<ContextProps>;live:()=>boolean}|null{
 const entry=entries.find(row=>row.options.key==='context'&&(row.options.priority??0)===0)
 if(!entry||entry.inject||entry.children||entry.store||!entry.component)return null
 return {component:entry.component as ComponentType<ContextProps>,live:()=>isLive(entry)}
}

/**
 * 会话里的上下文行：只有宿主交付复核追加的「复核后交付」改为可直接阅读、复制的交付卡，明确标为宿主按复核
 * 编辑计划生成（不是模型原文）；其余所有上下文仍交给原生 renderer。编辑计划本身留在原生助手记录里供审计。
 */
export function DeliveryReviewContextView({renderer,...props}:ContextProps&{renderer:Renderer}){
 const entries=useSyncExternalStore(renderer.subscribe,renderer.getSnapshot,renderer.getSnapshot)
 const native=nativeContextRenderer(entries,renderer.isLive)
 const delivery=readHostReviewDelivery(props.node.data)
 if(delivery)return <HostReviewDeliveryCard delivery={delivery}/>
 return native&&native.live()?createElement(native.component,props):null
}

export function HostReviewDeliveryCard({delivery}:{delivery:HostReviewDelivery}){
 const {locale}=useI18n()
 const copy=(zhCN:string,zhTW:string,en:string)=>locale==='zh-CN'?zhCN:locale.startsWith('zh')?zhTW:en
 const [verified,setVerified]=useState<boolean|null>(null),[copied,setCopied]=useState<'idle'|'done'|'failed'>('idle')
 useEffect(()=>{let live=true;setVerified(null);void verifyHostReviewDelivery(delivery).then(result=>{if(live)setVerified(result)},()=>{if(live)setVerified(false)});return ()=>{live=false}},[delivery.text,delivery.deliverySha256])
 const edits=delivery.edits===null?'':delivery.edits===0?copy('复核确认无需修改','複核確認無需修改','Review found no changes needed'):copy(`按复核编辑计划修改 ${delivery.edits} 处`,`依複核編輯計畫修改 ${delivery.edits} 處`,`${delivery.edits} edit${delivery.edits===1?'':'s'} applied from the review plan`)
 return <section className={css.card} aria-label={copy('复核后交付','複核後交付','Reviewed delivery')}>
  <article className={css.body}><MarkdownPreview markdown={delivery.text} images={false}/></article>
  <footer className={css.footer}>
   <ToolbarIconButton label={copy('复制交付全文','複製交付全文','Copy full delivery')} icon={copied==='done'?Check:Copy} onClick={()=>{void navigator.clipboard.writeText(delivery.text).then(()=>setCopied('done'),()=>setCopied('failed'))}}/>
   <details className={css.provenance}><summary>{copy('复核记录','複核記錄','Review details')}</summary><p>{copy('由宿主按模型复核编辑计划生成，不是模型原文','由宿主依模型複核編輯計畫產生，不是模型原文','Generated by the host from the model’s review edit plan; not the model’s own text')}{edits?' · '+edits:''}</p></details>
   <span aria-live="polite">{copied==='done'?copy('已复制','已複製','Copied'):copied==='failed'?copy('复制失败','複製失敗','Copy failed'):''}</span>
   {verified===false&&<span role="alert" className={css.warning}>{copy('正文与宿主记录的交付摘要不一致，请核对任务结果。','內文與宿主記錄的交付摘要不一致，請核對任務結果。','This text does not match the host’s recorded delivery hash; check the task result.')}</span>}
  </footer>
 </section>
}
